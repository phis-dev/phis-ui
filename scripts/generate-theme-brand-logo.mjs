import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

import { LETTERS, SLASH } from "./phis-wordmark.mjs";

/*
 * Generates theme/phi-theme-brand-logo.ts: the two inline SVGs the core "Phis" Set offers as its Logo.
 *
 * The wordmark "phi/s" in two tones, the drawing in scripts/phis-wordmark.mjs sheared by 14 degrees:
 * the letters in the text base of the mode, the slash in the brand orange. The frame is the drawing's
 * own bounds, round caps included, measured on the sheared strokes with a unit to spare: the shear moves
 * the top of the s far past where the letters stand upright, and a frame taken from the upright drawing
 * cut it off. So the picture sits flush wherever it is placed, with nothing clipped and nothing empty.
 *
 * Run with `node scripts/generate-theme-brand-logo.mjs` after changing the drawing or the colours.
 */

const STROKE = 64;
const ACCENT = "#E05A2A";

function stroke(d, color) {
  return `<path d="${d}" fill="none" stroke="${color}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round"/>`;
}

function logo(ink) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="44 -433 1007 586" width="1007" height="586"><g transform="translate(107.7 0) skewX(-14)">${stroke(LETTERS, ink)}${stroke(SLASH, ACCENT)}</g></svg>`;
}

const light = logo("#223A61");
const dark = logo("#DCE7F8");
const toDataUrl = (svg) => `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;

const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../theme/phi-theme-brand-logo.ts");
writeFileSync(target, `/**
 * The Logo the core "Phis" Set offers, one per mode.
 *
 * The wordmark "phi/s" in two tones: the letters in the text base of the mode, the slash in the brand
 * orange. Vector, inline, under a kilobyte each. Inline because a Set lives in code; the save that
 * takes the Logo into a Site's record uploads it into the Media library, so a Site never depends on this
 * file for a Logo it kept.
 *
 * Generated by scripts/generate-theme-brand-logo.mjs; edit the drawing there, not here.
 */
export const PHI_THEME_PHIS_BRAND_LOGO_LIGHT = ${JSON.stringify(toDataUrl(light))};

export const PHI_THEME_PHIS_BRAND_LOGO_DARK = ${JSON.stringify(toDataUrl(dark))};
`);
console.log(`wrote ${path.relative(process.cwd(), target)} (${light.length} + ${dark.length} bytes of SVG)`);
