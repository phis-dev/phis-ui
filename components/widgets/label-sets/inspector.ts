export async function getPhiInspectorWidgetLabels(
  options: PhiGlobalTranslatorOptions,
): Promise<PhiInspectorWidgetLabels> {
  const labels = await getPhiLabelSet(options, PHI_INSPECTOR_WIDGET_LABEL_SET);
  return {
    region: labels.region,
    layout: labels.layout,
    surface: labels.surface,
    widget: labels.widget,
    sections: {
      settings: labels.section_settings,
      geometry: labels.section_geometry,
      anchor: labels.section_anchor,
      viewport: labels.section_viewport,
      padding: labels.section_padding,
      background: labels.section_background,
      border: labels.section_border,
      shadow: labels.section_shadow,
      surface: labels.section_surface,
      signals: labels.section_signals,
    },
    surfaceStyle: {
      title: labels.surface_style_title,
      none: labels.surface_style_none,
      card: labels.surface_style_card,
      wash: labels.surface_style_wash,
      custom: labels.surface_style_custom,
    },
    tone: {
      title: labels.tone_title,
      inherit: labels.tone_inherit,
      light: labels.tone_light,
      dark: labels.tone_dark,
      inverse: labels.tone_inverse,
    },
    grid: {
      columns: labels.grid_columns,
      masonryColumns: labels.grid_masonry_columns,
      distribution: labels.grid_distribution,
      slot: labels.grid_slot,
      profiles: {
        compact: labels.grid_profile_compact,
        medium: labels.grid_profile_medium,
        wide: labels.grid_profile_wide,
      },
    },
    fields: {
      typeOrSelect: labels.field_type_or_select,
      noMatchingOptions: labels.field_no_matching_options,
      noItems: labels.field_no_items,
      addItem: labels.field_add_item,
      remove: labels.field_remove,
      edit: labels.field_edit,
      width: labels.field_width,
      height: labels.field_height,
      staticOptions: labels.field_static_options,
      selectDataProvider: labels.field_select_data_provider,
      selectTreeResource: labels.field_select_tree_resource,
      selectCollectionResource: labels.field_select_collection_resource,
      selectTableResource: labels.field_select_table_resource,
      selectCalendar: labels.field_select_calendar,
      selectVideoProvider: labels.field_select_video_provider,
      linkTarget: {
        none: labels.link_none,
        page: labels.link_page,
        external: labels.link_external,
        pagePlaceholder: labels.link_page_placeholder,
        landingPage: labels.link_landing_page,
        newTab: labels.link_new_tab,
        externalPlaceholder: PHI_INSPECTOR_WIDGET_DEFAULT_LABELS.fields.linkTarget.externalPlaceholder,
      },
    },
  };
}
